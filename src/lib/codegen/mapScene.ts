/** Inline centroid helper for exported scenes — duplicated from src/lib/geo.ts
    so the exported file has no studio dependencies. */
function emitCentroidHelper(): string {
  return `
function _centroid(geojson: any): [number, number] {
  if (!geojson) return [0, 0];
  if (geojson.type === "FeatureCollection") return _centroid(geojson.features?.[0]);
  if (geojson.type === "Feature") return _centroid(geojson.geometry);
  const t = geojson.type, c = geojson.coordinates;
  if (!c) return [0, 0];
  const ringCentroid = (ring: number[][]) => {
    let sx = 0, sy = 0, n = 0;
    const last = ring.length;
    const closed = last > 0 && ring[0][0] === ring[last-1][0] && ring[0][1] === ring[last-1][1];
    const upto = closed ? last - 1 : last;
    for (let i = 0; i < upto; i++) { sx += ring[i][0]; sy += ring[i][1]; n++; }
    return n === 0 ? [0, 0] : [sx / n, sy / n] as [number, number];
  };
  const ringArea = (ring: number[][]) => {
    let a = 0; for (let i = 0; i < ring.length - 1; i++) a += ring[i][0]*ring[i+1][1] - ring[i+1][0]*ring[i][1];
    return Math.abs(a/2);
  };
  if (t === "Polygon") return ringCentroid(c[0]);
  if (t === "MultiPolygon") {
    let best = c[0]?.[0] ?? [], bestArea = ringArea(best);
    for (let i = 1; i < c.length; i++) {
      const r = c[i][0], ar = ringArea(r);
      if (ar > bestArea) { bestArea = ar; best = r; }
    }
    return ringCentroid(best);
  }
  if (t === "LineString") return ringCentroid(c);
  if (t === "Point") return c as [number, number];
  return [0, 0];
}
`;
}

