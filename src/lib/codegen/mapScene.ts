/** Emit the easing function expression matching the selected EasingName */
function easingExpr(name: string): string {
  switch (name) {
    case "linear":
      return "(t: number) => t";
    case "easeIn":
      return "(t: number) => t * t";
    case "easeOut":
      return "(t: number) => t * (2 - t)";
    case "easeInOut":
      return "(t: number) => (t < 0.5 ? 2 * t * t : -1 + (4 - 2 * t) * t)";
    case "smooth":
      return "(t: number) => t * t * (3 - 2 * t)";
    case "cinematic":
      return "(t: number) => t * t * t * (t * (6 * t - 15) + 10)";
    default:
      return "(t: number) => (t < 0.5 ? 2 * t * t : -1 + (4 - 2 * t) * t)";
  }
}

