// safeInterpolate: drop-in replacement for Remotion's interpolate that
// never throws on degenerate ranges (e.g. start.zoom === end.zoom).
const fixMonotonic = (arr: number[]) => {
  const out = [arr[0]];
  for (let i = 1; i < arr.length; i++) {
    out.push(arr[i] <= out[i - 1] ? out[i - 1] + 0.001 : arr[i]);
  }
  return out;
};
const sInterp = (
  input: number,
  range: number[],
  output: number[],
  opts?: { extrapolateLeft?: "clamp" | "extend"; extrapolateRight?: "clamp" | "extend" }
) => interpolate(input, fixMonotonic(range), output, opts);

