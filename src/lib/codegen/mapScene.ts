// Camera path helpers (inlined from src/lib/interp.ts for self-contained exports)
const _catmullRom = (p0: number, p1: number, p2: number, p3: number, t: number): number => {
  const t2 = t * t, t3 = t2 * t;
  return 0.5 * (2*p1 + (-p0+p2)*t + (2*p0-5*p1+4*p2-p3)*t2 + (-p0+3*p1-3*p2+p3)*t3);
};
const _catmullRomChain = (values: number[], progress: number): number => {
  const N = values.length;
  if (N === 0) return 0;
  if (N === 1) return values[0];
  if (N === 2) return values[0] + (values[1] - values[0]) * progress;
  const c = Math.max(0, Math.min(1, progress));
  const seg = Math.min(N - 2, Math.floor(c * (N - 1)));
  const segT = c * (N - 1) - seg;
  const p1 = values[seg], p2 = values[seg + 1];
  const p0 = seg === 0 ? 2 * p1 - p2 : values[seg - 1];
  const p3 = seg + 2 >= N ? 2 * p2 - p1 : values[seg + 2];
  return _catmullRom(p0, p1, p2, p3, segT);
};
// linearChain: piecewise linear with smoothstep easing per segment.
// CAN'T overshoot — used for zoom/pitch to kill terrain wobble.
const _linearChain = (values: number[], progress: number): number => {
  const N = values.length;
  if (N === 0) return 0;
  if (N === 1) return values[0];
  if (N === 2) {
    const t = Math.max(0, Math.min(1, progress));
    const sm = t * t * (3 - 2 * t);
    return values[0] + (values[1] - values[0]) * sm;
  }
  const c = Math.max(0, Math.min(1, progress));
  const seg = Math.min(N - 2, Math.floor(c * (N - 1)));
  const t = c * (N - 1) - seg;
  const sm = t * t * (3 - 2 * t);
  return values[seg] + (values[seg + 1] - values[seg]) * sm;
};

// Route helpers (mirrors src/remotion/MapScene.tsx). Ease-in-out cubic shared
// by the line draw, vehicle icon and camera-follow so nothing desyncs; plus an
// arc-length sampler for constant-speed, interpolated motion along the path.
const _routeEase = (p: number): number =>
  p < 0.5 ? 4 * p * p * p : 1 - Math.pow(-2 * p + 2, 3) / 2;
const _sampleRouteAt = (coords: [number, number][], t: number): { lon: number; lat: number; bearing: number } => {
  const n = coords.length;
  if (n === 0) return { lon: 0, lat: 0, bearing: 0 };
  if (n === 1) return { lon: coords[0][0], lat: coords[0][1], bearing: 0 };
  const seg: number[] = []; let total = 0;
  for (let i = 0; i < n - 1; i++) { const d = Math.hypot(coords[i+1][0]-coords[i][0], coords[i+1][1]-coords[i][1]); seg.push(d); total += d; }
  const bearingOf = (a: [number, number], b: [number, number]) => (Math.atan2(b[0]-a[0], b[1]-a[1]) * 180) / Math.PI;
  if (total === 0) return { lon: coords[0][0], lat: coords[0][1], bearing: 0 };
  const c = Math.max(0, Math.min(1, t));
  if (c <= 0) return { lon: coords[0][0], lat: coords[0][1], bearing: bearingOf(coords[0], coords[1]) };
  if (c >= 1) return { lon: coords[n-1][0], lat: coords[n-1][1], bearing: bearingOf(coords[n-2], coords[n-1]) };
  let target = c * total;
  for (let i = 0; i < seg.length; i++) {
    if (target <= seg[i] || i === seg.length - 1) {
      const f = seg[i] > 0 ? target / seg[i] : 0;
      const a = coords[i], b = coords[i+1];
      return { lon: a[0]+(b[0]-a[0])*f, lat: a[1]+(b[1]-a[1])*f, bearing: bearingOf(a, b) };
    }
    target -= seg[i];
  }
  const last = coords[n-1];
  return { lon: last[0], lat: last[1], bearing: bearingOf(coords[n-2], last) };
};

