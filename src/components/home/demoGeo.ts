/** Find a curated sea lane connecting the first and last recognised stop. */
export function seaLaneFor(stops: { label: string }[]): [number, number][] | null {
  if (stops.length < 2) return null;
  const a = stops[0].label.trim().toLowerCase();
  const b = stops[stops.length - 1].label.trim().toLowerCase();
  return SEA_LANES[`${a}>${b}`] ?? SEA_LANES[`${b}>${a}`]?.slice().reverse() ?? null;
}

